// Copies the design system CSS into src/design/. Run via `npm run sync:design`.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const header = "/* Generated by scripts/sync-design.mjs from design/system. Do not edit. */\n";
const out = join(root, "src", "design");
mkdirSync(out, { recursive: true });
for (const name of ["tokens.css", "components.css"]) {
  writeFileSync(join(out, name), header + readFileSync(join(root, "..", "design", "system", name), "utf8"));
}
