import { expect, test } from "vitest";

const copies = import.meta.glob<string>("./design/*.css", { query: "?raw", import: "default", eager: true });
const sources = import.meta.glob<string>("../../design/system/*.css", { query: "?raw", import: "default", eager: true });
const allCss = import.meta.glob<string>("./**/*.css", { query: "?raw", import: "default", eager: true });

test.each(["tokens.css", "components.css"])("src/design/%s matches design/system (run npm run sync:design)", (name) => {
  const [header, ...rest] = copies[`./design/${name}`].split("\n");
  expect(header).toBe("/* Generated by scripts/sync-design.mjs from design/system. Do not edit. */");
  expect(rest.join("\n")).toBe(sources[`../../design/system/${name}`]);
});

test("CSS outside src/design uses tokens only (no literal colours or fonts)", () => {
  const bad: string[] = [];
  for (const [file, text] of Object.entries(allCss)) {
    if (file.startsWith("./design/")) continue;
    const css = text.replace(/\/\*[\s\S]*?\*\//g, "");
    for (const m of css.matchAll(/#[0-9a-fA-F]{3,8}\b|\b(?:rgba?|hsla?|oklch|oklab|lab|lch|hwb)\(/g)) bad.push(`${file}: ${m[0]}`);
    for (const m of css.matchAll(/font-family\s*:\s*([^;}]+)/g)) {
      if (!/^(?:var\(--font-[\w-]+\)|inherit)$/.test(m[1].trim())) bad.push(`${file}: font-family ${m[1].trim()}`);
    }
    // The `font:` shorthand ends with the family, so the value must end in a font token (or be `inherit`).
    for (const m of css.matchAll(/(?<![\w-])font\s*:\s*([^;}]+)/g)) {
      if (!/(?:\bvar\(--font-[\w-]+\)|^inherit)$/.test(m[1].trim())) bad.push(`${file}: font ${m[1].trim()}`);
    }
  }
  expect(bad).toEqual([]);
});
