// Generates tokens.css from tokens.json and fails if any listed colour pair misses WCAG AA.
// Usage: node design/system/build-tokens.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('.', import.meta.url);
const t = JSON.parse(readFileSync(new URL('tokens.json', dir), 'utf8'));

const outOfGamut = new Set();

function luminance(oklch) {
  const [L, C, h] = oklch.match(/oklch\(([^)]+)\)/)[1].split('/')[0].trim().split(/\s+/).map(Number);
  const a = C * Math.cos((h * Math.PI) / 180), b = C * Math.sin((h * Math.PI) / 180);
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const rgb = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
  if (rgb.some((v) => v < -0.002 || v > 1.002)) outOfGamut.add(oklch);
  const [r, g, bl] = rgb.map((v) => Math.min(1, Math.max(0, v)));
  return 0.2126 * r + 0.7152 * g + 0.0722 * bl;
}
const ratio = (fg, bg) => {
  const [hi, lo] = [luminance(fg), luminance(bg)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

let failed = 0;
const measured = [];
for (const mode of ['dark', 'light']) {
  for (const [fg, bg, min] of t.contrast) {
    const r = ratio(t.color[fg][mode], t.color[bg][mode]);
    const ok = r >= min;
    if (!ok) failed++;
    measured.push({ mode, fg, bg, min, ratio: Number(r.toFixed(2)) });
    console.log(`${ok ? 'pass' : 'FAIL'}  ${mode.padEnd(5)} ${fg} on ${bg}: ${r.toFixed(2)} (needs ${min})`);
  }
}

const rem = (px) => `${px / 16}rem`;
const modeVars = (mode) => [
  ...Object.entries(t.color).map(([k, v]) => `  --color-${k}: ${v[mode]};`),
  ...Object.entries(t.elevation).map(([k, v]) => `  --elevation-${k}: ${v[mode]};`),
  `  color-scheme: ${mode};`,
].join('\n');

const shared = [
  ...Object.entries(t.font).map(([k, v]) => `  --font-${k}: "${v.family}", ${v.fallback};`),
  ...Object.entries(t.type).flatMap(([k, v]) => [
    `  --type-${k}-font: var(--font-${v.font});`,
    `  --type-${k}-size: ${rem(v.size)};`,
    `  --type-${k}-line-height: ${rem(v.lineHeight)};`,
    `  --type-${k}-weight: ${v.weight};`,
    `  --type-${k}-tracking: ${v.tracking}em;`,
  ]),
  ...Object.entries(t.space).map(([k, v]) => `  --space-${k}: ${v}px;`),
  ...Object.entries(t.radius).map(([k, v]) => `  --radius-${k}: ${v}px;`),
  ...Object.entries(t.border).map(([k, v]) => `  --border-${k}: ${v}px;`),
  ...Object.entries(t.size).map(([k, v]) => `  --size-${k}: ${v}px;`),
  ...Object.entries(t.motion.duration).map(([k, v]) => `  --duration-${k}: ${v}ms;`),
  ...Object.entries(t.motion.easing).map(([k, v]) => `  --easing-${k}: cubic-bezier(${v.join(', ')});`),
].join('\n');

writeFileSync(new URL('tokens.css', dir), `/* Generated by build-tokens.mjs from tokens.json. Do not edit by hand. */
:root {
${shared}
}

:root,
[data-theme="dark"] {
${modeVars('dark')}
}

[data-theme="light"] {
${modeVars('light')}
}

@media (prefers-reduced-motion: reduce) {
  :root { --duration-fast: 0ms; --duration-base: 0ms; --duration-slow: 0ms; }
}
`);

// The showcase reads this; a plain script still loads when index.html is opened from disk.
writeFileSync(new URL('tokens.js', dir), `/* Generated by build-tokens.mjs. Do not edit by hand. */\nwindow.MH_TOKENS = ${JSON.stringify({ ...t, measured })};\n`);

for (const c of outOfGamut) console.log(`FAIL  ${c} is outside sRGB; lower its chroma`);
if (failed || outOfGamut.size) {
  console.error(`\n${failed} pair(s) below WCAG AA, ${outOfGamut.size} colour(s) outside sRGB`);
  process.exit(1);
}
console.log('\ntokens.css written; all pairs meet WCAG AA');
