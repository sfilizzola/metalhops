// Downloads the Lucide icons the showcase uses and writes icons.js (an inline SVG sprite).
// Usage: node design/system/build-icons.mjs   (needs network; add names to ICONS and re-run)
import { writeFileSync } from 'node:fs';

const VERSION = '0.469.0';
const ICONS = ['check', 'circle-alert', 'circle-dot', 'columns-2', 'image-off', 'info', 'lock', 'mail', 'map-pin', 'map-pin-check', 'map-pinned', 'message-square-off', 'moon', 'music', 'plus', 'refresh-cw', 'search', 'star', 'sun', 'target', 'trash-2', 'trees', 'utensils'];

const symbols = await Promise.all(ICONS.map(async (name) => {
  const res = await fetch(`https://unpkg.com/lucide-static@${VERSION}/icons/${name}.svg`);
  if (!res.ok) throw new Error(`Lucide has no icon "${name}" (${res.status})`);
  const svg = await res.text();
  const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s*\n\s*/g, '');
  return `<symbol id="i-${name}" viewBox="0 0 24 24">${inner}</symbol>`;
}));

const sprite = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none"><!-- Lucide ${VERSION}, ISC licence -->${symbols.join('')}</svg>`;
writeFileSync(new URL('icons.js', import.meta.url), `/* Generated by build-icons.mjs from Lucide ${VERSION} (ISC licence). Do not edit by hand. */\ndocument.body.insertAdjacentHTML('afterbegin', ${JSON.stringify(sprite)});\n`);
console.log(`icons.js written with ${ICONS.length} icons`);
